// Bundles every src/<step>/help.md into src/help.generated.ts so the help text works
// in Vite, Node and tests without loaders. Run: pnpm --filter @plotlab/steps gen:help
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const src = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
export function generate(): string {
  const entries: string[] = [];
  for (const d of readdirSync(src, { withFileTypes: true })) {
    const f = join(src, d.name, "help.md");
    if (d.isDirectory() && existsSync(f)) entries.push(`  ${JSON.stringify(d.name)}: ${JSON.stringify(readFileSync(f, "utf8"))},`);
  }
  entries.sort();
  return `// GENERATED by scripts/gen-help.ts from src/*/help.md. Do not edit.\nexport const help: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(src, "help.generated.ts"), generate());
}
